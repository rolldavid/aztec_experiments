#!/usr/bin/env python3
"""Prune inactive generated SDK outputs only; default is read-only.
Run after publication has finished, with no deployment writer in flight.
Plan: {candidates:[absolute release roots], protected:[current/candidate/rollback roots]}.
Neither manifests, source, dependencies, credentials nor by-hash assets are removed.
"""
import collections, hashlib, json, os, pathlib, re, shutil, stat, subprocess, sys
P=pathlib.Path
ROOTS=tuple(P('/opt')/name/'releases' for name in ('rolling-app','rolling-bok','rolling-moderator','board-prover'))
NATIVE_ARTIFACT_OUTPUTS=frozenset('native-contract-'+name+'.json' for name in ('AuthRegistry','ContractClassRegistry','ContractInstanceRegistry','FeeJuice','HandshakeRegistry','MultiCallEntrypoint'))
PAT=r'/opt/(?:rolling-[a-z-]+|board-prover)/releases/[A-Za-z0-9._-]+'
def digest(path):
 with path.open('rb') as stream:return hashlib.file_digest(stream,'sha256').hexdigest()
def identity(info):return (info.st_dev,info.st_ino,info.st_size,info.st_mtime_ns,info.st_ctime_ns)
def regular(path):
 info=path.lstat()
 assert stat.S_ISREG(info.st_mode) and path.resolve()==path and info.st_uid==os.getuid()
 return info
def release(path,roots=ROOTS):
 assert path.parent in roots and re.fullmatch(r'[A-Za-z0-9._-]+',path.name) and path.name not in ('.','..')
 assert path.is_dir() and not path.is_symlink() and path.resolve()==path
 return path

def references():
 found=set()
 def add(data):found.update(P(value) for value in re.findall(PAT,data))
 def read(path,vanishing=False):
  try:add(path.read_bytes().decode('utf8',errors='ignore'))
  except (FileNotFoundError,ProcessLookupError):
   if not vanishing:raise
 def link(path,vanishing=False):
  try:add(os.readlink(path))
  except (FileNotFoundError,ProcessLookupError):
   if not vanishing:raise
 # Configuration text is read locally, never returned; only release roots leave this function.
 for folder in ('/etc/systemd/system','/run/systemd/system','/etc/rolling-app','/etc/rolling-bok','/etc/rolling-bok-testnet','/etc/rolling-moderator','/etc/board-prover','/etc/rolling-node','/etc/rolling-query'):
  root=P(folder)
  if not root.exists():continue
  for path in root.rglob('*'):
   if path.is_symlink():
    link(path)
    if path.is_file():read(path)
   elif path.is_file():read(path)
 for path in P('/usr/local/lib').glob('rolling*'):
  if path.is_file():read(path)
 # Include effective loaded unit state, including units not present under /etc.
 units=subprocess.check_output(['systemctl','list-units','--all','--type=service','--no-legend','--plain'],text=True)
 names=[line.split()[0] for line in units.splitlines() if line.split()]
 for name in names:
  assert re.fullmatch(r'[A-Za-z0-9_.@:\\-]+\.service',name)
 if names:add(subprocess.check_output(['systemctl','show',*names,'-p','WorkingDirectory','-p','RootDirectory','-p','ExecStart','-p','ExecStartPre','-p','ExecStartPost','-p','Environment','-p','EnvironmentFiles'],text=True))
 for proc in P('/proc').iterdir():
  if not proc.name.isdigit():continue
  try:
   for name in ('cmdline','maps'):read(proc/name,True)
   for name in ('cwd','exe','root'):link(proc/name,True)
   for descriptor in (proc/'fd').iterdir():link(descriptor,True)
  except (FileNotFoundError,ProcessLookupError):pass
 for folder in P('/opt').iterdir():
  if folder.name.startswith('rolling-') or folder.name=='board-prover':
   for path in folder.iterdir() if folder.is_dir() else ():
    if path.is_symlink():add(str(path.resolve()))
 return found

def collect(plan,refs,roots=ROOTS):
 assert set(plan)=={'candidates','protected'} and plan['protected']
 candidates=[release(P(path),roots) for path in plan['candidates']]
 assert len(candidates)==len(set(candidates))
 keep={P(path) for path in plan['protected']}|refs
 rows=[];manifests={}
 for root in candidates:
  if root in keep:continue
  manifest=root/'.build/sdk/sdk-manifest.json'
  if not manifest.exists():continue
  regular(manifest);manifest_hash=digest(manifest);value=json.loads(manifest.read_text());outputs=value['outputs'];assert isinstance(outputs,dict)
  manifests[str(manifest)]=manifest_hash
  for name,want in outputs.items():
   assert (re.fullmatch(r'[A-Za-z0-9_.-]+\.(?:js|mjs|wasm)',name) or name in NATIVE_ARTIFACT_OUTPUTS) and re.fullmatch('[a-f0-9]{64}',want)
   path=manifest.parent/name
   if not path.exists() and not path.is_symlink():continue
   # Old generated bytes may differ from their old manifest. They are disposable;
   # confinement and positive live-reference protection govern deletion.
   info=regular(path)
   rows.append({'path':str(path),'release':str(root),'sha256':want,'device':info.st_dev,'inode':info.st_ino,'size':info.st_size,'mtime':info.st_mtime_ns,'ctime':info.st_ctime_ns,'allocated':info.st_blocks*512,'links':info.st_nlink})
 return rows,manifests,keep

def reclaimable(rows):
 grouped=collections.defaultdict(list)
 for row in rows:grouped[row['device'],row['inode']].append(row)
 return sum(group[0]['allocated'] for group in grouped.values() if len(group)==group[0]['links'])

def prune(plan,apply=False,refs_fn=references,roots=ROOTS):
 initial=refs_fn();rows,manifests,keep=collect(plan,initial,roots)
 # Snapshot the whole candidate set before unlink, then recheck references.
 for path,want in manifests.items():regular(P(path));assert digest(P(path))==want
 for row in rows:
  info=regular(P(row['path']));assert identity(info)==(row['device'],row['inode'],row['size'],row['mtime'],row['ctime']) and info.st_nlink==row['links']
 assert refs_fn()==initial,'References changed; no files removed'
 result={'applied':apply,'files':len(rows),'logicalBytes':sum(row['size'] for row in rows),'reclaimableAllocatedBytes':reclaimable(rows),'protected':sorted(map(str,keep)),'manifestHashes':manifests}
 if not apply:return result
 before=shutil.disk_usage('/').free
 grouped=collections.defaultdict(list)
 for row in rows:grouped[row['device'],row['inode']].append(row)
 for group in grouped.values():
  first=group[0];fd=os.open(first['path'],os.O_RDONLY|os.O_NOFOLLOW)
  try:
   expected=os.fstat(fd)
   assert identity(expected)==(first['device'],first['inode'],first['size'],first['mtime'],first['ctime']) and expected.st_nlink==first['links']
   for row in group:
    path=P(row['path']);info=regular(path)
    assert identity(info)==identity(expected) and info.st_nlink==expected.st_nlink
    path.unlink() # Unlink only; never truncate a shared inode or follow a symlink.
    after=os.fstat(fd)
    assert (after.st_dev,after.st_ino,after.st_size,after.st_mtime_ns)==(expected.st_dev,expected.st_ino,expected.st_size,expected.st_mtime_ns) and after.st_nlink==expected.st_nlink-1
    expected=after # Only our unlink advances ctime/link count for the next alias.
  finally:os.close(fd)
 result['freeBefore']=before;result['freeAfter']=shutil.disk_usage('/').free
 return result

def main():
 assert os.getuid()==0
 assert len(sys.argv) in (2,3) and (len(sys.argv)==2 or sys.argv[2]=='--apply')
 plan=P(sys.argv[1]);regular(plan)
 print(json.dumps(prune(json.loads(plan.read_text()),len(sys.argv)==3)))
if __name__=='__main__':main()
